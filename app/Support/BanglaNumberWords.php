<?php

namespace App\Support;

/**
 * Whole taka in Bangla words, the way a work order writes its total:
 * 45500 → "পঁয়তাল্লিশ হাজার পাঁচশত টাকা মাত্র".
 *
 * Uses the Bangladeshi grouping: কোটি (10^7), লক্ষ (10^5), হাজার, শত.
 */
class BanglaNumberWords
{
    /** 0–99 each have their own word in Bangla; there is no pattern to build them from. */
    private const UNDER_100 = [
        'শূন্য', 'এক', 'দুই', 'তিন', 'চার', 'পাঁচ', 'ছয়', 'সাত', 'আট', 'নয়',
        'দশ', 'এগারো', 'বারো', 'তেরো', 'চৌদ্দ', 'পনেরো', 'ষোলো', 'সতেরো', 'আঠারো', 'উনিশ',
        'বিশ', 'একুশ', 'বাইশ', 'তেইশ', 'চব্বিশ', 'পঁচিশ', 'ছাব্বিশ', 'সাতাশ', 'আটাশ', 'ঊনত্রিশ',
        'ত্রিশ', 'একত্রিশ', 'বত্রিশ', 'তেত্রিশ', 'চৌত্রিশ', 'পঁয়ত্রিশ', 'ছত্রিশ', 'সাঁইত্রিশ', 'আটত্রিশ', 'ঊনচল্লিশ',
        'চল্লিশ', 'একচল্লিশ', 'বিয়াল্লিশ', 'তেতাল্লিশ', 'চুয়াল্লিশ', 'পঁয়তাল্লিশ', 'ছেচল্লিশ', 'সাতচল্লিশ', 'আটচল্লিশ', 'ঊনপঞ্চাশ',
        'পঞ্চাশ', 'একান্ন', 'বাহান্ন', 'তিপ্পান্ন', 'চুয়ান্ন', 'পঞ্চান্ন', 'ছাপ্পান্ন', 'সাতান্ন', 'আটান্ন', 'ঊনষাট',
        'ষাট', 'একষট্টি', 'বাষট্টি', 'তেষট্টি', 'চৌষট্টি', 'পঁয়ষট্টি', 'ছেষট্টি', 'সাতষট্টি', 'আটষট্টি', 'ঊনসত্তর',
        'সত্তর', 'একাত্তর', 'বাহাত্তর', 'তিয়াত্তর', 'চুয়াত্তর', 'পঁচাত্তর', 'ছিয়াত্তর', 'সাতাত্তর', 'আটাত্তর', 'ঊনআশি',
        'আশি', 'একাশি', 'বিরাশি', 'তিরাশি', 'চুরাশি', 'পঁচাশি', 'ছিয়াশি', 'সাতাশি', 'আটাশি', 'ঊননব্বই',
        'নব্বই', 'একানব্বই', 'বিরানব্বই', 'তিরানব্বই', 'চুরানব্বই', 'পঁচানব্বই', 'ছিয়ানব্বই', 'সাতানব্বই', 'আটানব্বই', 'নিরানব্বই',
    ];

    public static function taka(int $amount): string
    {
        return self::words($amount).' টাকা মাত্র';
    }

    public static function words(int $n): string
    {
        if ($n === 0) {
            return self::UNDER_100[0];
        }

        $parts = [];

        // Above 99 কোটি the কোটি count itself is said in words (e.g. একশত কোটি).
        if ($n >= 10_000_000) {
            $parts[] = self::words(intdiv($n, 10_000_000)).' কোটি';
            $n %= 10_000_000;
        }

        foreach ([[100_000, 'লক্ষ'], [1_000, 'হাজার'], [100, 'শত']] as [$size, $name]) {
            if ($n >= $size) {
                $parts[] = self::UNDER_100[intdiv($n, $size)].($name === 'শত' ? '' : ' ').$name;
                $n %= $size;
            }
        }

        if ($n > 0) {
            $parts[] = self::UNDER_100[$n];
        }

        return implode(' ', $parts);
    }
}
